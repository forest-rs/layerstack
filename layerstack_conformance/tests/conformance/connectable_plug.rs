//! Connectable behaviors a codeless schema plugin's metadata configures,
//! against C++ (`scripts/connectable_plug_oracle.py`).
//!
//! The registry is built as a host builds one for a codeless plugin: the
//! plugin's `generatedSchema.usda` read with the kinds, bases, auto-applies
//! and other type keys its `plugInfo.json` declares
//! (`SchemaDeclaration::plug_info`), over OpenUSD's own domains.
use std::sync::Arc;

use layerstack::schema::{SchemaDeclaration, read_generated_schema};
use layerstack::{
    FieldEntry, FieldValue, LayerId, NoAssets, PropertyPath, SchemaKind, SchemaRegistry, Stage,
    StageOptions, TokenInterner, Value,
};
use layerstack_conformance::{usda_real::load_entry_usda, workspace_root};
use layerstack_schemas::{Domain, Scene};
use serde::Deserialize;
use serde_json::Value as Json;

#[derive(Deserialize)]
struct Oracle {
    openusd_version: String,
    prims: Vec<Prim>,
    connections: Vec<(String, String, bool)>,
    providers: Vec<(String, bool, Vec<String>)>,
}

#[derive(Deserialize)]
struct Prim {
    path: String,
    connectable: bool,
    is_container: bool,
    requires_encapsulation: bool,
}

/// The keys of a type entry the registry reads into fields of its own.
const REGISTRY_KEYS: [&str; 9] = [
    "alias",
    "autoGenerated",
    "bases",
    "schemaKind",
    "schemaIdentifier",
    "apiSchemaAutoApplyTo",
    "apiSchemaCanOnlyApplyTo",
    "apiSchemaAllowedInstanceNames",
    "apiSchemaInstances",
];

/// A `plugInfo.json` scalar as `SchemaDefinition::plug_info` holds it.
fn plug_value(json: &Json) -> Value {
    match json {
        Json::Bool(value) => Value::Bool(*value),
        Json::Number(number) => number
            .as_i64()
            .map_or_else(|| Value::Double(number.as_f64().unwrap()), Value::Int64),
        Json::String(text) => Value::String(text.as_str().into()),
        other => panic!("the fixture's plug info holds scalars, not {other}"),
    }
}

/// OpenUSD's domains, and the fixture plugin read as a host reads a
/// codeless plugin.
fn registry(tokens: &TokenInterner, paths: &layerstack::PathInterner) -> SchemaRegistry {
    let dir = workspace_root().join("layerstack_conformance/fixtures/connectable_plug/plugin");
    let plug_info: Json =
        serde_json::from_str(&std::fs::read_to_string(dir.join("plugInfo.json")).unwrap()).unwrap();
    let types = plug_info["Plugins"][0]["Info"]["Types"]
        .as_object()
        .unwrap();
    // The bases outside the plugin, by C++ type name.
    let base = |name: &str| match name {
        "UsdTyped" | "UsdAPISchemaBase" => None,
        "UsdShadeShader" => Some(tokens.intern("Shader")),
        own => Some(tokens.intern(types[own]["schemaIdentifier"].as_str().unwrap())),
    };
    let mut declared = Vec::new();
    let mut auto_applies = Vec::new();
    for entry in types.values() {
        let name = tokens.intern(entry["schemaIdentifier"].as_str().unwrap());
        let kind = match entry["schemaKind"].as_str().unwrap() {
            "concreteTyped" => SchemaKind::ConcreteTyped,
            "singleApplyAPI" => SchemaKind::SingleApplyApi,
            "multipleApplyAPI" => SchemaKind::MultipleApplyApi,
            other => panic!("schema kind {other}"),
        };
        for target in entry["apiSchemaAutoApplyTo"]
            .as_array()
            .into_iter()
            .flatten()
        {
            auto_applies.push((name, tokens.intern(target.as_str().unwrap())));
        }
        let plug_info = entry
            .as_object()
            .unwrap()
            .iter()
            .filter(|(key, _)| !REGISTRY_KEYS.contains(&key.as_str()))
            .map(|(key, value)| FieldEntry {
                name: tokens.intern(key),
                value: FieldValue::Value(plug_value(value)),
            })
            .collect();
        declared.push(SchemaDeclaration {
            parent: base(entry["bases"][0].as_str().unwrap()),
            plug_info,
            ..SchemaDeclaration::new(name, kind)
        });
    }
    let source = std::fs::read_to_string(dir.join("generatedSchema.usda")).unwrap();
    let read = layerstack_usda::read_usda(&source, LayerId(u64::MAX), tokens, paths, &mut NoAssets);
    let definitions = read_generated_schema(&read.emitted.layer, &declared, tokens, paths)
        .expect("every declared schema");
    let mut builder = SchemaRegistry::builder();
    layerstack_schemas::register(
        &mut builder,
        &[Domain::UsdGeom, Domain::UsdShade, Domain::UsdLux],
        tokens,
    )
    .unwrap();
    for definition in definitions {
        builder.register(definition);
    }
    for (api, target) in auto_applies {
        builder.auto_apply(api, target);
    }
    builder.build(tokens)
}

fn property(store: &layerstack::InMemoryStore, text: &str) -> PropertyPath {
    let (prim, name) = text.split_once('.').unwrap();
    PropertyPath::new(store.path(prim), store.tokens().intern(name))
}

#[test]
fn plug_metadata_behaviors_match_cpp() {
    let oracle: Oracle =
        serde_json::from_str(include_str!("../../fixtures/connectable_plug/oracle.json")).unwrap();
    assert_eq!(oracle.openusd_version, "0.26.11");
    let scene_path =
        workspace_root().join("layerstack_conformance/fixtures/connectable_plug/scene.usda");
    let mut loaded = load_entry_usda(&scene_path);
    let store = &mut loaded.store;
    let registry = Arc::new(registry(store.tokens(), store.paths()));
    assert!(registry.issues().is_empty(), "{:?}", registry.issues());
    let options = StageOptions {
        schemas: Some(registry),
        ..StageOptions::default()
    };
    let stage = Stage::compose(store, loaded.root_layer, options);
    let store = &*store;
    let scene = Scene::new(&stage, store);
    let mut failures = Vec::new();
    for prim in &oracle.prims {
        let behavior = scene.connectable_behavior(store.path(&prim.path));
        let ours = (
            behavior.is_some(),
            behavior.is_some_and(|b| b.is_container),
            behavior.is_some_and(|b| b.requires_encapsulation),
        );
        let theirs = (
            prim.connectable,
            prim.is_container,
            prim.requires_encapsulation,
        );
        if ours != theirs {
            failures.push(format!(
                "{} (connectable, container, encapsulation): layerstack {ours:?}, C++ {theirs:?}",
                prim.path
            ));
        }
    }
    for (destination, source, allowed) in &oracle.connections {
        let ours = scene
            .validate_shading_connection(property(store, destination), property(store, source));
        if ours.is_ok() != *allowed {
            failures.push(format!(
                "{destination} <- {source}: layerstack {ours:?}, C++ allowed {allowed}"
            ));
        }
    }
    // Value-producing attributes pass through the containers plugin
    // metadata configures, as through built-in ones.
    for (input, outputs_only, theirs) in &oracle.providers {
        let input = property(store, input);
        let ours: Vec<PropertyPath> = if *outputs_only {
            let found = scene.shader_sources(input);
            found.sources.iter().map(|source| source.output).collect()
        } else {
            let found = scene.value_sources(input);
            found
                .sources
                .iter()
                .map(|source| source.attribute)
                .collect()
        };
        let ours: Vec<String> = ours
            .iter()
            .map(|path| path.display(store.paths(), store.tokens()))
            .collect();
        if &ours != theirs {
            failures.push(format!(
                "providers of {input:?} (outputs only {outputs_only}): layerstack {ours:?}, \
                 C++ {theirs:?}"
            ));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}
