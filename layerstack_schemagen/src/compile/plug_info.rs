//! The library's `plugInfo.json`: usdGenSchema's `GeneratePlugInfo` and
//! `_UpdatePlugInfoWithAPISchemaApplyInfo`, written as its `json.dumps`
//! writes it.

use std::fmt::Write as _;

use layerstack::Value;
use serde_json::{Map, Number, Value as Json};

use super::CompileError;
use super::classes::{ClassInfo, Parsed, dict_get};

/// usdGenSchema's comment header. Comment lines are dropped when an
/// existing file is read, and this one is written again.
const HEADER: &str = "# Portions of this file auto-generated by usdGenSchema.\n\
                      # Edits will survive regeneration except for comments and\n\
                      # changes to types with autoGenerated=true.\n";

/// The plugInfo for `parsed`'s classes, built on `existing` (an earlier
/// `plugInfo.json`) as usdGenSchema builds on the file already in its
/// output directory, or else on its `codegenTemplates/plugInfo.json`.
pub(crate) fn generate(
    parsed: &Parsed,
    existing: Option<&str>,
    tokens: &layerstack::TokenInterner,
) -> Result<String, CompileError> {
    let error = |message: String| CompileError::PlugInfo { message };
    let mut info = match existing {
        Some(text) => {
            let json: String = text
                .lines()
                .filter(|line| !line.trim_start().starts_with('#'))
                .flat_map(|line| [line, "\n"])
                .collect();
            serde_json::from_str(&json).map_err(|e| error(e.to_string()))?
        }
        None => template(&parsed.library.name),
    };
    let library = &parsed.library;
    let types = if let Some(plugins) = info.get_mut("Plugins") {
        let plugins = plugins
            .as_array_mut()
            .ok_or_else(|| error("Plugins is not a list".into()))?;
        let mut types = None;
        for plugin in plugins {
            let plugin = plugin
                .as_object_mut()
                .ok_or_else(|| error("a plugin is not an object".into()))?;
            // A codeless library's plugin holds resources, not a library.
            if library.skip_code_generation {
                plugin.insert("Type".into(), Json::String("resource".into()));
            }
            if plugin.get("Name").and_then(Json::as_str) == Some(library.name.as_str()) {
                types = Some(object_entry(object_entry(plugin, "Info")?, "Types")?);
                break;
            }
        }
        types.ok_or_else(|| {
            error(format!(
                "Could not find plugin metadata section for {}",
                library.name
            ))
        })?
    } else {
        object_entry(
            info.as_object_mut()
                .ok_or_else(|| error("not an object".into()))?,
            "Types",
        )?
    };
    types.retain(|_, entry| {
        !entry
            .get("autoGenerated")
            .and_then(Json::as_bool)
            .unwrap_or(false)
    });
    for class in &parsed.classes {
        types.insert(class.cpp_class_name.clone(), type_entry(class, tokens)?);
    }
    let mut out = String::from(HEADER);
    write_json(&info, 0, &mut out);
    out.push('\n');
    Ok(out)
}

/// The installed form of `plug_info` (as [`generate`] writes it), for a
/// plugin directory holding it and `generatedSchema.usda` in `resources/`:
/// the template's placeholders filled in as OpenUSD's build fills them for
/// that layout (`Root` `..`, `ResourcePath` `resources`, and for a codeless
/// library an empty `LibraryPath`), and no comment lines, so it is strict
/// JSON. Values that are not placeholders are kept.
pub(crate) fn install(plug_info: &str, codeless: bool) -> Result<String, CompileError> {
    let error = |message: String| CompileError::PlugInfo { message };
    let json: String = plug_info
        .lines()
        .filter(|line| !line.trim_start().starts_with('#'))
        .flat_map(|line| [line, "\n"])
        .collect();
    let mut info: Json = serde_json::from_str(&json).map_err(|e| error(e.to_string()))?;
    let plugins = info
        .get_mut("Plugins")
        .and_then(Json::as_array_mut)
        .ok_or_else(|| error("Plugins is not a list".into()))?;
    for plugin in plugins {
        let plugin = plugin
            .as_object_mut()
            .ok_or_else(|| error("a plugin is not an object".into()))?;
        for (key, placeholder, installed) in [
            ("Root", "@PLUG_INFO_ROOT@", ".."),
            ("ResourcePath", "@PLUG_INFO_RESOURCE_PATH@", "resources"),
            ("LibraryPath", "@PLUG_INFO_LIBRARY_PATH@", ""),
        ] {
            let Some(value) = plugin.get_mut(key) else {
                continue;
            };
            if value.as_str() != Some(placeholder) {
                continue;
            }
            if key == "LibraryPath" && !codeless {
                return Err(error(
                    "a library with code is installed by its build, which knows its LibraryPath"
                        .into(),
                ));
            }
            *value = Json::String(installed.into());
        }
    }
    let mut out = String::new();
    write_json(&info, 0, &mut out);
    out.push('\n');
    Ok(out)
}

/// `codegenTemplates/plugInfo.json`, with `libraryName` filled in. The
/// `@PLUG_INFO_...@` placeholders are what OpenUSD's build configures.
fn template(library: &str) -> Json {
    let mut plugin = Map::new();
    let mut info = Map::new();
    info.insert("Types".into(), Json::Object(Map::new()));
    plugin.insert("Info".into(), Json::Object(info));
    for (key, value) in [
        ("LibraryPath", "@PLUG_INFO_LIBRARY_PATH@"),
        ("Name", library),
        ("ResourcePath", "@PLUG_INFO_RESOURCE_PATH@"),
        ("Root", "@PLUG_INFO_ROOT@"),
        ("Type", "library"),
    ] {
        plugin.insert(key.into(), Json::String(value.into()));
    }
    let mut root = Map::new();
    root.insert("Plugins".into(), Json::Array(vec![Json::Object(plugin)]));
    Json::Object(root)
}

/// `dict.setdefault(key, {})`, as an object.
fn object_entry<'a>(
    object: &'a mut Map<String, Json>,
    key: &str,
) -> Result<&'a mut Map<String, Json>, CompileError> {
    object
        .entry(key)
        .or_insert_with(|| Json::Object(Map::new()))
        .as_object_mut()
        .ok_or_else(|| CompileError::PlugInfo {
            message: format!("{key} is not an object"),
        })
}

/// A class's `Types` entry.
fn type_entry(class: &ClassInfo, tokens: &layerstack::TokenInterner) -> Result<Json, CompileError> {
    let mut entry = Map::new();
    // extraPlugInfo goes first, so the generated keys win.
    if let Some(Value::Dictionary(extra)) = dict_get(&class.custom_data, "extraPlugInfo") {
        for (key, value) in extra {
            let value = value
                .as_value()
                .and_then(|value| to_json(value, tokens))
                .ok_or_else(|| CompileError::PlugInfo {
                    message: format!(
                        "{}'s extraPlugInfo `{key}` has no JSON representation",
                        class.name
                    ),
                })?;
            entry.insert(key.to_string(), value);
        }
    }
    entry.insert(
        "bases".into(),
        Json::Array(vec![Json::String(class.parent_cpp_class_name.clone())]),
    );
    entry.insert("autoGenerated".into(), Json::Bool(true));
    entry.insert(
        "schemaKind".into(),
        Json::String(class.kind.as_str().into()),
    );
    if class.is_applied {
        let list =
            |names: &[String]| Json::Array(names.iter().cloned().map(Json::String).collect());
        if !class.auto_apply_to.is_empty() {
            entry.insert("apiSchemaAutoApplyTo".into(), list(&class.auto_apply_to));
        }
        if !class.can_only_apply_to.is_empty() {
            entry.insert(
                "apiSchemaCanOnlyApplyTo".into(),
                list(&class.can_only_apply_to),
            );
        }
        if !class.allowed_instance_names.is_empty() {
            entry.insert(
                "apiSchemaAllowedInstanceNames".into(),
                list(&class.allowed_instance_names),
            );
        }
        let instances: Map<String, Json> = class
            .instance_can_only_apply_to
            .iter()
            .filter(|(_, to)| !to.is_empty())
            .map(|(instance, to)| {
                let mut info = Map::new();
                info.insert("apiSchemaCanOnlyApplyTo".into(), list(to));
                (instance.clone(), Json::Object(info))
            })
            .collect();
        if !instances.is_empty() {
            entry.insert("apiSchemaInstances".into(), Json::Object(instances));
        }
    }
    if class.name != class.cpp_class_name {
        let mut alias = Map::new();
        alias.insert("UsdSchemaBase".into(), Json::String(class.name.clone()));
        entry.insert("alias".into(), Json::Object(alias));
    }
    entry.insert("schemaIdentifier".into(), Json::String(class.name.clone()));
    Ok(Json::Object(entry))
}

/// A customData value as `_ConvertDictionaryForJSON` and `json.dumps`
/// see it.
fn to_json(value: &Value, tokens: &layerstack::TokenInterner) -> Option<Json> {
    Some(match value {
        Value::Bool(b) => Json::Bool(*b),
        Value::Int(v) => Json::Number((*v).into()),
        Value::UInt(v) => Json::Number((*v).into()),
        Value::Int64(v) => Json::Number((*v).into()),
        Value::UInt64(v) => Json::Number((*v).into()),
        Value::UChar(v) => Json::Number((*v).into()),
        Value::Float(v) => Json::Number(Number::from_f64(f64::from(*v))?),
        Value::Double(v) => Json::Number(Number::from_f64(*v)?),
        Value::String(text) => Json::String(text.to_string()),
        Value::Token(token) => Json::String(tokens.resolve(*token).to_owned()),
        Value::Array(_) | Value::TypedArray(_) => Json::Array(
            value
                .array_ref()?
                .iter()
                .map(|item| to_json(&item, tokens))
                .collect::<Option<_>>()?,
        ),
        Value::Dictionary(entries) => Json::Object(
            entries
                .iter()
                .map(|(key, value)| Some((key.to_string(), to_json(value.as_value()?, tokens)?)))
                .collect::<Option<_>>()?,
        ),
        _ => return None,
    })
}

/// Writes `value` as Python's `json.dumps(value, indent=4, sort_keys=True,
/// separators=(', ', ': '))` does: keys sorted, non-ASCII escaped, and
/// each item separator keeping its space before the line break.
pub(crate) fn write_json(value: &Json, depth: usize, out: &mut String) {
    let indent = |out: &mut String, depth: usize| {
        for _ in 0..depth {
            out.push_str("    ");
        }
    };
    match value {
        Json::Null => out.push_str("null"),
        Json::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
        Json::Number(number) => write_number(number, out),
        Json::String(text) => write_string(text, out),
        Json::Array(items) if items.is_empty() => out.push_str("[]"),
        Json::Array(items) => {
            out.push_str("[\n");
            for (i, item) in items.iter().enumerate() {
                if i > 0 {
                    out.push_str(", \n");
                }
                indent(out, depth + 1);
                write_json(item, depth + 1, out);
            }
            out.push('\n');
            indent(out, depth);
            out.push(']');
        }
        Json::Object(entries) if entries.is_empty() => out.push_str("{}"),
        Json::Object(entries) => {
            let mut keys: Vec<&String> = entries.keys().collect();
            keys.sort();
            out.push_str("{\n");
            for (i, key) in keys.into_iter().enumerate() {
                if i > 0 {
                    out.push_str(", \n");
                }
                indent(out, depth + 1);
                write_string(key, out);
                out.push_str(": ");
                write_json(&entries[key], depth + 1, out);
            }
            out.push('\n');
            indent(out, depth);
            out.push('}');
        }
    }
}

/// An integer as itself; a float as Python's `repr` writes it.
fn write_number(number: &Number, out: &mut String) {
    if number.is_f64() {
        let value = number.as_f64().expect("a float");
        out.push_str(&python_float_repr(value));
    } else {
        let _ = write!(out, "{number}");
    }
}

/// Python's `repr` of a finite float: the shortest digits that read back,
/// in positional form for exponents from -4 to 15 (with `.0` for an
/// integral value), else in scientific form (`1e-05`, `1.5e+16`).
fn python_float_repr(value: f64) -> String {
    let scientific = format!("{value:e}");
    let (mantissa, exponent) = scientific.split_once('e').expect("an exponent");
    let exponent: i32 = exponent.parse().expect("a decimal exponent");
    if (-4..16).contains(&exponent) {
        let text = format!("{value}");
        if text.contains('.') || text.contains("inf") || text.contains("NaN") {
            text
        } else {
            format!("{text}.0")
        }
    } else {
        let sign = if exponent < 0 { '-' } else { '+' };
        format!("{mantissa}e{sign}{:02}", exponent.abs())
    }
}

/// A JSON string with Python's escapes (`ensure_ascii`).
fn write_string(text: &str, out: &mut String) {
    out.push('"');
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            c if c.is_ascii() && !c.is_ascii_control() => out.push(c),
            c => {
                let mut units = [0; 2];
                for unit in c.encode_utf16(&mut units) {
                    let _ = write!(out, "\\u{unit:04x}");
                }
            }
        }
    }
    out.push('"');
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn floats_are_written_as_python_writes_them() {
        for (value, text) in [
            (1.0, "1.0"),
            (0.5, "0.5"),
            (1e-5, "1e-05"),
            (0.0001, "0.0001"),
            (1e16, "1e+16"),
            (123_456_789_012_345.0, "123456789012345.0"),
            (-2.5e-7, "-2.5e-07"),
        ] {
            assert_eq!(python_float_repr(value), text);
        }
    }

    #[test]
    fn json_is_written_as_python_writes_it() {
        let json: Json =
            serde_json::from_str(r#"{"b": [1, "\u00e9"], "a": {}, "c": [], "d": {"x": true}}"#)
                .unwrap();
        let mut out = String::new();
        write_json(&json, 0, &mut out);
        assert_eq!(
            out,
            "{\n    \"a\": {}, \n    \"b\": [\n        1, \n        \"\\u00e9\"\n    ], \n    \
             \"c\": [], \n    \"d\": {\n        \"x\": true\n    }\n}"
        );
    }
}
