/// The comment usdGenSchema gives the generated layer.
const COMMENT: &str = "WARNING: THIS FILE IS GENERATED BY usdGenSchema.  DO NOT EDIT.";

/// `MAX_LENGTH_FOR_USERDOCBRIEF`.
const MAX_BRIEF: usize = 500;

/// Generates `generatedSchema.usda` for `parsed`'s classes from the schema
/// stage (`GenerateRegistry`).
///
/// The stage is flattened, so each class holds the properties and
/// metadata its inherited classes compose into it; then each class keeps
/// only its own documentation, which becomes a brief `userDocBrief`;
/// classes of other libraries and `/GLOBAL` are removed; a multiple-apply
/// schema's properties get its instanceable prefix; and `customData` keeps
/// only what the schema registry reads.
///
/// Spec: AOUSD Core §13.3 (prim definitions), §11 (flattening a stage).
pub(crate) fn generate(
    stage: &mut SchemaStage,
    parsed: &Parsed,
    source: &FsPath,
    search: &[PathBuf],
) -> Result<String, CompileError> {
    let user_doc = UserDoc::open(source, search)?;
    let layer_stack = stage.layer_stack();
    let root = stage.root;
    let flat = flatten(stage, root)?;
    let (store, _) = stage.parts_mut();
    let names = Names::new(store);
    let target = EditTarget::for_layer(flat);

    // `_MakeFlattenedRegistryLayer`: a class keeps the documentation the
    // layers of the stack author for it, never an inherited class's; the
    // weakest layer authoring the class prim decides.
    let mut docs = Transaction::new();
    for &layer in &layer_stack {
        let Some(layer) = store.layer(layer) else {
            continue;
        };
        for path in root_prims(layer, store) {
            if store
                .layer(flat)
                .expect("the flattened layer")
                .prim(path)
                .is_none()
            {
                continue;
            }
            let at = target.prim(path);
            match layer
                .prim(path)
                .and_then(|spec| spec.field(names.documentation))
            {
                Some(doc) => docs.set_metadata(at, names.documentation, doc.clone()),
                None => docs.clear_metadata(at, names.documentation),
            };
        }
    }
    apply(&docs, store)?;

    let briefs = briefs(
        store.layer(flat).expect("the flattened layer"),
        store,
        &names,
        user_doc.as_ref(),
    );

    let mut edit = Transaction::new();
    let flat_layer = store.layer(flat).expect("the flattened layer");
    let flat_roots = root_prims(flat_layer, store);
    for &path in &flat_roots {
        let spec = flat_layer.prim(path).expect("a flattened root prim");
        edit.clear_metadata(target.prim(path), names.documentation);
        for entry in &spec.properties {
            edit.clear_metadata(
                target.property(PropertyPath::new(path, entry.name)),
                names.documentation,
            );
        }
    }
    let mut fallback_prim_types: Vec<(String, Vec<String>)> = Vec::new();
    let mut removed = Vec::new();
    for &path in &flat_roots {
        let name = store.paths().resolve(path).display(store.tokens());
        let name = name.trim_start_matches('/');
        let Some(class) = parsed.classes.iter().find(|class| class.name == name) else {
            removed.push(path);
            continue;
        };
        let spec = flat_layer.prim(path).expect("a flattened root prim");
        let custom_data = custom_data(spec.field(names.custom_data));
        let mut properties: Vec<String> = spec
            .properties
            .iter()
            .map(|entry| store.tokens().resolve(entry.name).to_owned())
            .collect();
        if super::names::family_and_version(name).0.ends_with("API") {
            let api_schema_type = dict_str(&custom_data, "apiSchemaType", store.tokens())
                .unwrap_or_else(|| SINGLE_APPLY.into());
            if api_schema_type == MULTIPLE_APPLY {
                properties = rename_with_prefix(
                    class,
                    &custom_data,
                    &properties,
                    path,
                    &target,
                    store,
                    &mut edit,
                )?;
            }
            check_api_metadata(class, spec, &api_schema_type, &names, store)?;
        }
        if spec.type_name.is_some() {
            let types = dict_strings(&custom_data, "fallbackTypes", store.tokens());
            if !types.is_empty() {
                fallback_prim_types.push((name.to_owned(), types));
            }
        }
        let at = target.prim(path);
        if !class.all_applied_api_schemas.is_empty() {
            let mut list = ListOp::new();
            list.explicit = Some(
                class
                    .all_applied_api_schemas
                    .iter()
                    .map(|s| store.tokens().intern(s))
                    .collect(),
            );
            edit.set_metadata(
                at.clone(),
                names.api_schemas,
                FieldValue::TokenListOp(Box::new(list)),
            );
        }
        // The registry reads only the override names and the brief docs
        // from customData.
        let mut data = Vec::new();
        let mut overrides = class.api_schema_override_property_names.clone();
        overrides.sort();
        if !overrides.is_empty() {
            data.push((
                Arc::from("apiSchemaOverridePropertyNames"),
                Value::Array(
                    overrides
                        .iter()
                        .map(|n| Value::Token(store.tokens().intern(n)))
                        .collect(),
                )
                .into(),
            ));
        }
        if let Some(brief) = briefs.get(&(name.to_owned(), None)) {
            data.push((
                Arc::from("userDocBrief"),
                Value::String(Arc::from(&**brief)).into(),
            ));
        }
        set_custom_data(&mut edit, at, data, &names);
        for property in &properties {
            let lookup = if is_multiple_apply_name_template(property) {
                property.rsplit(':').next().unwrap_or(property)
            } else {
                property.as_str()
            };
            let data = briefs
                .get(&(name.to_owned(), Some(lookup.to_owned())))
                .map(|brief| {
                    (
                        Arc::from("userDocBrief"),
                        Value::String(Arc::from(&**brief)).into(),
                    )
                })
                .into_iter()
                .collect();
            let at = target.property(PropertyPath::new(path, store.tokens().intern(property)));
            set_custom_data(&mut edit, at, data, &names);
        }
    }
    for path in removed {
        edit.remove_spec(target.prim(path));
    }
    edit.set_layer_metadata(
        flat,
        names.comment,
        FieldValue::Value(Value::String(Arc::from(COMMENT))),
    );
    if !fallback_prim_types.is_empty() {
        fallback_prim_types.sort();
        let types = fallback_prim_types
            .into_iter()
            .map(|(name, types)| {
                (
                    Arc::from(name.as_str()),
                    Value::Array(
                        types
                            .iter()
                            .map(|t| Value::Token(store.tokens().intern(t)))
                            .collect(),
                    )
                    .into(),
                )
            })
            .collect();
        edit.set_layer_metadata(
            flat,
            store.tokens().intern("fallbackPrimTypes"),
            FieldValue::Value(Value::Dictionary(types)),
        );
    }
    apply(&edit, store)?;
    write(store.layer(flat).expect("the flattened layer"), store)
}

/// Interned field names.
struct Names {
    documentation: layerstack::TokenId,
    custom_data: layerstack::TokenId,
    api_schemas: layerstack::TokenId,
    comment: layerstack::TokenId,
}

impl Names {
    fn new(store: &layerstack::InMemoryStore) -> Self {
        let tokens = &store.tokens();
        Self {
            documentation: tokens.intern("documentation"),
            custom_data: tokens.intern("customData"),
            api_schemas: tokens.intern("apiSchemas"),
            comment: tokens.intern("comment"),
        }
    }
}

/// Flattens the schema stage into a new layer of its store, as
/// `UsdStage::Flatten` does. The stage composes with no schema registry,
/// so no prim definition decides a property, which usdGenSchema avoids by
/// mangling type names. Asset paths stay as authored: the schema stage
/// knows no layer locations.
fn flatten(stage: &mut SchemaStage, root: LayerId) -> Result<LayerId, CompileError> {
    let (store, composed) = stage.parts_mut();
    let id = LayerId(store.layer_ids().last().map_or(0, |id| id.0) + 1);
    let requirements = FlattenRequirements {
        asset_paths: AssetPaths::AsAuthored,
        ..FlattenRequirements::default()
    };
    let flattened = composed
        .flatten(store, &layerstack::NoAssets, root, id, &requirements)
        .map_err(|e| CompileError::Write {
            message: format!("flattening the schema stage: {e:?}"),
        })?;
    store.insert_layer(flattened.layer);
    Ok(id)
}

fn apply(edit: &Transaction, store: &mut layerstack::InMemoryStore) -> Result<(), CompileError> {
    edit.apply(store)
        .map(drop)
        .map_err(|e| CompileError::Write {
            message: format!("editing the flattened layer: {e:?}"),
        })
}

/// The root prims of `layer`, in its order.
fn root_prims(layer: &Layer, store: &layerstack::InMemoryStore) -> Vec<PathId> {
    let root = store.paths().intern(Path::root());
    layer
        .prim(root)
        .map(|spec| {
            spec.authored_children
                .iter()
                .map(|&name| store.paths().intern(Path::root().join(&[name])))
                .collect()
        })
        .unwrap_or_default()
}

fn custom_data(field: Option<&FieldValue>) -> Vec<(Arc<str>, FieldValue)> {
    match field {
        Some(FieldValue::Value(Value::Dictionary(entries))) => entries.clone(),
        _ => Vec::new(),
    }
}

/// Replaces customData with `data`, or clears it when `data` is empty.
fn set_custom_data(
    edit: &mut Transaction,
    at: layerstack::Address,
    data: Vec<(Arc<str>, FieldValue)>,
    names: &Names,
) {
    if data.is_empty() {
        edit.clear_metadata(at, names.custom_data);
    } else {
        edit.set_metadata(
            at,
            names.custom_data,
            FieldValue::Value(Value::Dictionary(data)),
        );
    }
}

/// `_RenamePropertiesWithInstanceablePrefix`: each property of a
/// multiple-apply schema copied to `prefix:__INSTANCE_NAME__:name` (the
/// `__INSTANCE_NAME__` property to `prefix:__INSTANCE_NAME__`), then the
/// originals removed, so the order stays. Returns the new names.
fn rename_with_prefix(
    class: &ClassInfo,
    custom_data: &[(Arc<str>, FieldValue)],
    properties: &[String],
    path: PathId,
    target: &EditTarget,
    store: &layerstack::InMemoryStore,
    edit: &mut Transaction,
) -> Result<Vec<String>, CompileError> {
    if properties.is_empty() {
        return Ok(Vec::new());
    }
    let prefix = dict_get(custom_data, "propertyNamespacePrefix")
        .filter(|value| is_truthy(value, store.tokens()))
        .and_then(|value| super::classes::value_str(value, store.tokens()))
        .ok_or_else(|| CompileError::Schema {
            path: format!("/{}", class.name),
            rule: Rule::PropertiesWithoutPrefix,
        })?;
    let mut renamed = Vec::with_capacity(properties.len());
    for name in properties {
        let base = if name == super::names::INSTANCE_NAME_PLACEHOLDER {
            ""
        } else {
            name
        };
        let new = multiple_apply_name_template(&prefix, base);
        if properties.contains(&new) || renamed.contains(&new) {
            return Err(CompileError::Schema {
                path: format!("/{}", class.name),
                rule: Rule::PrefixedPropertyExists { name: new },
            });
        }
        edit.copy_spec(
            target.property(PropertyPath::new(path, store.tokens().intern(name))),
            target.property(PropertyPath::new(path, store.tokens().intern(&new))),
        );
        renamed.push(new);
    }
    for name in properties {
        edit.remove_spec(target.property(PropertyPath::new(path, store.tokens().intern(name))));
    }
    Ok(renamed)
}

/// `GenerateRegistry`: an API schema provides prim metadata fallbacks only
/// for `documentation` (and `customData`, which is removed), plus
/// `apiSchemas` when it is applied, and `propertyOrder` and `uiHints` when
/// it is single-apply.
fn check_api_metadata(
    class: &ClassInfo,
    spec: &PrimSpec,
    api_schema_type: &str,
    names: &Names,
    store: &layerstack::InMemoryStore,
) -> Result<(), CompileError> {
    let mut allowed = vec!["specifier", "customData", "documentation"];
    if api_schema_type == SINGLE_APPLY || api_schema_type == MULTIPLE_APPLY {
        allowed.push("apiSchemas");
    }
    if api_schema_type == SINGLE_APPLY {
        allowed.push("propertyOrder");
        allowed.push("uiHints");
    }
    let mut authored: Vec<String> = spec
        .fields
        .iter()
        .filter(|field| field.name != names.documentation)
        .map(|field| store.tokens().resolve(field.name).to_owned())
        .collect();
    for (key, present) in [
        ("typeName", spec.type_name.is_some()),
        ("propertyOrder", spec.property_order().is_some()),
        ("primOrder", spec.prim_order().is_some()),
        ("active", spec.active.is_some()),
        ("instanceable", spec.instanceable.is_some()),
    ] {
        if present {
            authored.push(key.into());
        }
    }
    authored.sort();
    let fields: Vec<String> = authored
        .into_iter()
        .filter(|key| !allowed.contains(&key.as_str()))
        .collect();
    if fields.is_empty() {
        return Ok(());
    }
    Err(CompileError::Schema {
        path: format!("/{}", class.name),
        rule: Rule::InvalidApiMetadata {
            fields,
            api_schema_type: api_schema_type.into(),
            allowed,
        },
    })
}

/// The brief docs of the flattened classes and their properties, keyed by
/// class name and property name (`_UpdateUserDocForRegistry`).
fn briefs(
    flat: &Layer,
    store: &layerstack::InMemoryStore,
    names: &Names,
    user_doc: Option<&UserDoc>,
) -> BTreeMap<(String, Option<String>), String> {
    let mut briefs = BTreeMap::new();
    for path in root_prims(flat, store) {
        let class = store.paths().resolve(path).display(store.tokens());
        let class = class.trim_start_matches('/').to_owned();
        if class == "GLOBAL" {
            continue;
        }
        let spec = flat.prim(path).expect("a root prim");
        let user = user_doc.and_then(|doc| doc.custom_data(&class, None));
        if let Some(brief) = brief(
            user.as_deref(),
            &custom_data(spec.field(names.custom_data)),
            spec.field(names.documentation),
        ) {
            briefs.insert((class.clone(), None), brief);
        }
        for entry in &spec.properties {
            let property = store.tokens().resolve(entry.name).to_owned();
            let user = user_doc.and_then(|doc| doc.custom_data(&class, Some(&property)));
            if let Some(brief) = brief(
                user.as_deref(),
                &custom_data(entry.spec.metadata(names.custom_data)),
                entry.spec.metadata(names.documentation),
            ) {
                briefs.insert((class.clone(), Some(property)), brief);
            }
        }
    }
    briefs
}

/// `_GetUserDocForSchemaObj`: `userDocBrief` from the user doc, else from
/// the object's customData, else the first sentence of its
/// documentation, at most 500 characters.
fn brief(
    user: Option<&[(Arc<str>, FieldValue)]>,
    custom_data: &[(Arc<str>, FieldValue)],
    documentation: Option<&FieldValue>,
) -> Option<String> {
    let brief_of = |data: &[(Arc<str>, FieldValue)]| match dict_get(data, "userDocBrief") {
        Some(Value::String(text)) => Some(text.trim().to_owned()),
        _ => None,
    };
    if let Some(brief) = user.and_then(brief_of) {
        return Some(brief);
    }
    if let Some(brief) = brief_of(custom_data) {
        return Some(brief);
    }
    let Some(FieldValue::Value(Value::String(doc))) = documentation else {
        return None;
    };
    if doc.is_empty() {
        return None;
    }
    let end = [". ", ".\n"]
        .iter()
        .filter_map(|delimiter| doc.find(delimiter))
        .min()
        .unwrap_or(doc.len());
    let mut sentence = doc[..end].trim().to_owned();
    if sentence.chars().count() > MAX_BRIEF {
        sentence = sentence.chars().take(MAX_BRIEF).collect::<String>() + "...";
    } else if !sentence.is_empty() && !sentence.ends_with('.') {
        sentence.push('.');
    }
    Some(sentence)
}

/// A schema's `userDoc/schemaUserDoc.usda`, composed: the user doc it
/// authors for its classes and properties, over the schema it sublayers.
struct UserDoc {
    stage: SchemaStage,
    custom_data: layerstack::TokenId,
}

impl UserDoc {
    fn open(source: &FsPath, search: &[PathBuf]) -> Result<Option<Self>, CompileError> {
        let path = source
            .parent()
            .unwrap_or(FsPath::new("."))
            .join("userDoc")
            .join("schemaUserDoc.usda");
        if !path.is_file() {
            return Ok(None);
        }
        let stage = SchemaStage::open(&path, search)?;
        let custom_data = stage.store().tokens().intern("customData");
        Ok(Some(Self { stage, custom_data }))
    }

    /// The composed customData of the class, or of its property.
    fn custom_data(
        &self,
        class: &str,
        property: Option<&str>,
    ) -> Option<Vec<(Arc<str>, FieldValue)>> {
        let store = self.stage.store();
        let class = store
            .paths()
            .lookup(&Path::root().join(&[store.tokens().lookup(class)?]))?;
        let class = self.stage.view().prim(class)?;
        let resolved = match property {
            None => class
                .metadata(self.custom_data)
                .and_then(layerstack::Resolved::into_value)
                .map(|resolved| resolved.value),
            Some(property) => {
                store.tokens().lookup(property)?;
                class
                    .property(property)
                    .and_then(|property| property.metadata(self.custom_data))
                    .and_then(|resolved| match resolved.value {
                        layerstack::ResolvedValue::Dictionary(entries) => {
                            Some(Value::Dictionary(entries))
                        }
                        layerstack::ResolvedValue::Scalar(value) => Some(value),
                        _ => None,
                    })
            }
        };
        Some(match resolved {
            Some(Value::Dictionary(entries)) => entries,
            _ => Vec::new(),
        })
    }
}

/// Writes the generated layer as `SdfLayer::ExportToString` writes it:
/// every field in key order (an `SdfLayer` keeps its fields in a map),
/// the layer's comment first, dictionaries in key order, then without the
/// doxygen commands usdGenSchema removes from the text.
fn write(layer: &Layer, store: &layerstack::InMemoryStore) -> Result<String, CompileError> {
    let mut document = layerstack_usda::save::usdc_document(layer, store.tokens(), store.paths())
        .map_err(|e| CompileError::Write {
        message: e.to_string(),
    })?;
    sort_metadata(&mut document.metadata);
    for prim in &mut document.prims {
        sort_prim(prim);
    }
    document.to_usda().map_err(|e| CompileError::Write {
        message: e.to_string(),
    })
}

fn sort_prim(prim: &mut Prim) {
    sort_metadata(&mut prim.metadata);
    for property in &mut prim.properties {
        match property {
            Property::Attribute(attribute) => {
                sort_metadata(&mut attribute.metadata);
                if let Some(value) = &mut attribute.value {
                    clean_value(value);
                }
            }
            Property::Relationship(relationship) => sort_metadata(&mut relationship.metadata),
        }
    }
    for child in &mut prim.children {
        sort_prim(child);
    }
}

/// Metadata in key order (`documentation` for `doc`), the comment first.
fn sort_metadata(metadata: &mut [Metadatum]) {
    let key = |entry: &Metadatum| match entry.key.as_str() {
        "comment" => (0, String::new()),
        "doc" => (1, "documentation".to_owned()),
        other => (1, other.to_owned()),
    };
    metadata.sort_by_key(key);
    for entry in metadata {
        clean_value(&mut entry.value);
    }
}

/// Sorts dictionaries by key and removes, from text, the doxygen commands
/// usdGenSchema removes from the exported layer: `\em ` and `\ref` or
/// `\section` with their argument, and `\li` becomes `-`.
fn clean_value(value: &mut Text) {
    match value {
        Text::Dictionary(entries) => {
            entries.sort_by(|a, b| a.0.cmp(&b.0));
            for (_, value) in entries {
                clean_value(value);
            }
        }
        Text::String(text) | Text::Token(text) => *text = clean_text(text),
        Text::StringArray(items) | Text::TokenArray(items) => {
            for item in items {
                *item = clean_text(item);
            }
        }
        _ => {}
    }
}

/// The text with usdGenSchema's doxygen substitutions applied, in its
/// order.
fn clean_text(text: &str) -> String {
    if !text.contains('\\') {
        return text.to_owned();
    }
    let text = text.replace("\\em ", "").replace("\\li", "-");
    let text = remove_command(&text, "ref");
    remove_command(&text, "section")
}

/// Removes each `\+command \S+ `: one or more backslashes, the command, a
/// space, its argument and the space after it.
fn remove_command(text: &str, command: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    'scan: while let Some(start) = rest.find('\\') {
        out.push_str(&rest[..start]);
        let after = rest[start..].trim_start_matches('\\');
        if let Some(arg) = after
            .strip_prefix(command)
            .and_then(|tail| tail.strip_prefix(' '))
        {
            let length = arg.find(char::is_whitespace).unwrap_or(arg.len());
            if length > 0 && arg[length..].starts_with(' ') {
                rest = &arg[length + 1..];
                continue 'scan;
            }
        }
        // No match here: keep this backslash and look again after it.
        out.push('\\');
        rest = &rest[start + 1..];
    }
    out.push_str(rest);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn doxygen_commands_are_removed_as_usd_gen_schema_removes_them() {
        assert_eq!(clean_text("a \\em b"), "a b");
        assert_eq!(clean_text("\\li item"), "- item");
        assert_eq!(clean_text("see \\ref Foo_Bar for"), "see for");
        assert_eq!(clean_text("see \\ref Foo"), "see \\ref Foo");
        assert_eq!(clean_text("x \\\\section S y"), "x y");
        assert_eq!(clean_text("plain"), "plain");
    }

    #[test]
    fn briefs_are_first_sentences() {
        let doc = |text: &str| FieldValue::Value(Value::String(Arc::from(text)));
        assert_eq!(
            brief(None, &[], Some(&doc("First one. Second one."))),
            Some("First one.".into())
        );
        assert_eq!(
            brief(None, &[], Some(&doc("No period\nhere"))),
            Some("No period\nhere.".into())
        );
        assert_eq!(
            brief(None, &[], Some(&doc("file.usda is a file.\nNext"))),
            Some("file.usda is a file.".into())
        );
        assert_eq!(brief(None, &[], None), None);
    }
}
