//! The generated schema layer: usdGenSchema's `GenerateRegistry`,
//! `_MakeFlattenedRegistryLayer`, `_RenamePropertiesWithInstanceablePrefix`
//! and `_UpdateUserDocForRegistry`, done with layerstack's flatten and
//! transactions, and written as `SdfLayer::ExportToString` writes it.

